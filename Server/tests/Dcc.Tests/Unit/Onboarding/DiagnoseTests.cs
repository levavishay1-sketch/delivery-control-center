using System.Text.Json.Nodes;
using Dcc.Infrastructure.Onboarding;
using Dcc.Infrastructure.Repos;

namespace Dcc.Tests.Unit.Onboarding;

/// <summary>
/// The diagnosis (diagnose.test.ts) on a small synthetic repository whose facts are known: an npm monorepo with tests,
/// CI, generated code, one real secret and one placeholder, docs, a Dockerfile and a short git history in which three
/// commits change the same three files together. The profile is read back from its JSON, as the stored one is.
/// </summary>
public sealed class DiagnoseTests(DiagnoseTests.SyntheticMonorepo repo) : IClassFixture<DiagnoseTests.SyntheticMonorepo>
{
    private static void Write(string root, string rel, string content)
    {
        var abs = Path.Combine(root, rel);
        Directory.CreateDirectory(Path.GetDirectoryName(abs)!);
        File.WriteAllText(abs, content);
    }

    private static async Task GitAsync(string cwd, params string[] args)
    {
        var r = await Git.RunAsync(["-c", "user.name=t", "-c", "user.email=t@x", "-c", "commit.gpgsign=false", .. args], cwd);
        Assert.True(r.Ok, r.Out);
    }

    private static readonly string LongReadme = $"# Synthetic\n\n{string.Concat(Enumerable.Repeat("Lorem ipsum dolor sit amet, consectetur adipiscing elit. ", 160))}\n";

    private static async Task BuildRepoAsync(string root)
    {
        Write(root, "package.json", """
            {
              "name": "synthetic",
              "private": true,
              "workspaces": [
                "packages/*"
              ],
              "scripts": {
                "build": "tsc -b",
                "test": "vitest run"
              },
              "devDependencies": {
                "vitest": "^3.0.0",
                "eslint": "^9.0.0",
                "typescript": "^5.0.0"
              }
            }
            """.ReplaceLineEndings("\n"));
        Write(root, "packages/a/package.json", "{\n  \"name\": \"@synthetic/a\",\n  \"dependencies\": {\n    \"react\": \"^19.0.0\"\n  }\n}");
        Write(root, "src/__generated__/x.ts", "export const x = 1;\n");
        Write(root, "src/models.ts", "// <auto-generated>\n//     This code was generated by a tool.\n// </auto-generated>\nexport type Model = { id: string };\n");
        Write(root, "src/a.ts", "export const a = 1;\n");
        Write(root, "src/b.ts", "export const b = 1;\n");
        Write(root, "src/c.ts", "export const c = 1;\n");
        Write(root, "src/db.ts", string.Join("\n",
            "export const live = \"Server=db;Database=app;User Id=app;Password=Sup3rSecret;\";",
            "export const local = \"Server=localhost;Database=app;User Id=app;Password=changethis;\";",
            ""));
        Write(root, "tests/x.test.ts", "import { expect, it } from \"vitest\";\nit(\"works\", () => expect(1).toBe(1));\n");
        Write(root, ".github/workflows/ci.yml", "name: CI\non: [push]\njobs:\n  test:\n    runs-on: ubuntu-latest\n    steps:\n      - run: npm test\n      - run: npm run build\n");
        Write(root, ".env", "DB_HOST=localhost\n");
        Write(root, "README.md", LongReadme);
        Write(root, "docs/architecture.md", "# Architecture\n\nOne process, one database.\n");
        Write(root, "Dockerfile", "FROM node:22\nCOPY . /app\n");
        Write(root, ".eslintrc.json", "{}\n");

        await GitAsync(root, "init", "-q");
        await GitAsync(root, "add", "-A");
        await GitAsync(root, "commit", "-q", "-m", "initial");
        foreach (var n in new[] { 1, 2, 3 })
        {
            foreach (var f in new[] { "src/a.ts", "src/b.ts", "src/c.ts" }) Write(root, f, $"export const {Path.GetFileNameWithoutExtension(f)} = {n + 1};\n");
            await GitAsync(root, "add", "-A");
            await GitAsync(root, "commit", "-q", "-m", $"change {n}");
        }
        Write(root, "README.md", "# Synthetic\n\nRewritten.\n");
        await GitAsync(root, "add", "-A");
        await GitAsync(root, "commit", "-q", "-m", "readme");
        // The README on disk is the one the diagnosis measures; put the long one back after the history is made.
        Write(root, "README.md", LongReadme);
    }

    /// <summary>The profile as the database hands it back: parsed from its JSON.</summary>
    private static JsonObject Reparse(JsonObject profile) => JsonNode.Parse(profile.ToJsonString())!.AsObject();

    private static void Same(string expectedJson, JsonNode? actual) =>
        Assert.True(JsonNode.DeepEquals(JsonNode.Parse(expectedJson), actual), $"expected {expectedJson}, got {actual?.ToJsonString()}");

    private static List<string> Strings(JsonNode? array) => array!.AsArray().Select(x => x!.GetValue<string>()).ToList();

    private static string NewRoot() => Directory.CreateTempSubdirectory("dcc-diagnose-").FullName;

    /// <summary>One repository and one diagnosis for the tests that read it, as the old suite's beforeAll made them.</summary>
    public sealed class SyntheticMonorepo : IAsyncLifetime
    {
        public string Root { get; } = NewRoot();
        public JsonObject P { get; private set; } = null!;

        public async Task InitializeAsync()
        {
            await BuildRepoAsync(Root);
            P = Reparse(await RepositoryDiagnosis.DiagnoseAsync(Root, "synthetic"));
        }

        public Task DisposeAsync()
        {
            RepoCheckouts.ForceDelete(Root);
            return Task.CompletedTask;
        }
    }

    private JsonObject P => repo.P;

    [Fact]
    public void Names_the_repository_and_the_walked_files()
    {
        Assert.Equal("synthetic", P["name"]!.GetValue<string>());
        Assert.Equal(repo.Root, P["path"]!.GetValue<string>());
        Assert.Equal(15, P["size"]!["files"]!.GetValue<int>());
        Assert.Equal([".github", "docs", "packages", "src", "tests"], Strings(P["size"]!["top_level_dirs"]));
        Assert.True(P["size"]!["bytes_on_disk_excl_git"]!.GetValue<long>() > 9000);
    }

    [Fact]
    public void Sees_TypeScript_first_with_its_lines_counted()
    {
        var first = P["languages"]![0]!;
        Assert.Equal("TypeScript", first["language"]!.GetValue<string>());
        Assert.Equal(7, first["files"]!.GetValue<int>());
        Assert.True(first["lines"]!.GetValue<long>() > 0);
        Assert.Equal(first["lines"]!.GetValue<long>(), P["size"]!["code_lines"]!.GetValue<long>());
    }

    [Fact]
    public void Reads_the_manifests_frameworks_build_tests_lint()
    {
        Assert.Equal(["eslint", "react (sub-package)", "typescript", "vitest"], Strings(P["frameworks"]));
        Same("""{ "system": ["package.json scripts"], "commands": ["npm run build   # -> tsc -b"] }""", P["build"]);
        Same("""{ "frameworks": ["package.json:test -> vitest run", "vitest"], "test_files": 1, "test_dirs": [["tests", 1]] }""", P["tests"]);
        Assert.Equal(["eslint", ".eslintrc.json"], Strings(P["lint_format"]));
        Assert.Empty(Strings(P["package_managers"]));
    }

    [Fact]
    public void Recognises_the_workspaces_as_a_monorepo()
    {
        var mono = P["monorepo"]!;
        Assert.True(mono["is_monorepo"]!.GetValue<bool>());
        Assert.Equal(["packages/*"], Strings(mono["workspaces"]));
        Assert.Equal(["packages/a"], Strings(mono["packages"]));
        Assert.Equal(1, mono["package_count"]!.GetValue<int>());
    }

    [Fact]
    public void Finds_generated_code_by_path_and_by_header()
    {
        var gen = P["generated_code"]!;
        Same("""[{ "dir": "src/__generated__", "files": 1 }]""", gen["paths"]);
        Assert.Equal(1, gen["header_marked_files"]!.GetValue<int>());
        Assert.Equal(["src/models.ts"], Strings(gen["header_sample"]));
        Same("""[{ "dir": "src", "files": 1 }]""", gen["header_dirs"]);
    }

    [Fact]
    public void Counts_the_real_secret_and_not_the_placeholder_and_lists_the_sensitive_files()
    {
        var secrets = P["secrets"]!;
        Assert.Equal(1, secrets["total"]!.GetValue<int>());
        Assert.Equal(1, secrets["outside_tests"]!.GetValue<int>());
        Assert.Equal(0, secrets["in_test_files"]!.GetValue<int>());
        Same("""{ "connection_string_with_password": 1 }""", secrets["by_kind"]);
        Same("""[{ "path": "src/db.ts", "hits": 1 }]""", secrets["files"]);
        Assert.Contains(".env", Strings(secrets["sensitive_files"]));
        Assert.Empty(Strings(secrets["dotenv_examples"]));
    }

    [Fact]
    public void Reads_the_CI_workflow_and_its_commands()
    {
        var ci = P["ci"]!;
        Assert.True(ci["present"]!.GetValue<bool>());
        Assert.Equal(["github-actions"], Strings(ci["systems"]));
        Same("""[{ "file": ".github/workflows/ci.yml", "name": "CI" }]""", ci["workflows"]);
        Assert.Contains("npm test", Strings(ci["commands"]));
        Assert.Contains("npm run build", Strings(ci["commands"]));
        Assert.Equal(1, ci["workflow_count"]!.GetValue<int>());
    }

    [Fact]
    public void Measures_the_docs_and_the_environment()
    {
        var docs = P["docs"]!;
        Assert.Equal("README.md", docs["readme"]!.GetValue<string>());
        Assert.True(docs["readme_bytes"]!.GetValue<int>() >= 8000);
        Assert.True(docs["docs_dir"]!.GetValue<bool>());
        Assert.Contains("docs/architecture.md", Strings(docs["architecture_docs"]));
        Assert.Equal("none", docs["license_kind"]!.GetValue<string>());
        Assert.Empty(Strings(docs["pr_template"]));
        Assert.Empty(Strings(docs["codeowners"]));
        Assert.Equal(["Dockerfile"], Strings(P["environment"]!["dockerfile"]));
        Assert.Empty(Strings(P["environment"]!["docker_compose"]));
        Assert.NotNull(P["external_systems"]!["Docker"]);
        Same("""{ "present": false, "files": [], "count": 0, "kinds": [], "sizes": {} }""", P["ai_config"]);
        Assert.False(P["windows_build"]!["windows_only_build"]!.GetValue<bool>());
    }

    [Fact]
    public void Reads_the_git_history_the_three_files_that_always_change_together()
    {
        var g = P["git"]!;
        Assert.True(g["available"]!.GetValue<bool>());
        Assert.Equal(5, g["commits_in_clone"]!.GetValue<int>());
        Assert.Equal(5, g["commits_analyzed"]!.GetValue<int>());
        Assert.Equal(1, g["authors_in_clone"]!.GetValue<int>());
        Assert.False(g["shallow"]!.GetValue<bool>());
        Assert.Equal(15, g["tracked_files"]!.GetValue<int>());
        Same("""{ "files": ["src/a.ts", "src/b.ts", "src/c.ts"], "times": 3 }""", g["repeated_change_shapes"]![0]);
        Same("[]", g["cochange_pairs"]);
        Same("""{ "path": "src/a.ts", "changes": 4, "authors": 1 }""", g["hot_files"]![0]);
        // a, b and c four times each, and the four other .ts files once
        Assert.Equal(16, g["churn_by_ext"]![".ts"]!.GetValue<int>());
    }

    [Fact]
    public async Task Leaves_the_history_out_when_asked_to()
    {
        var root = NewRoot();
        try
        {
            await BuildRepoAsync(root);
            var p = Reparse(await RepositoryDiagnosis.DiagnoseAsync(root, "synthetic", git: false));
            Same("""{ "available": false }""", p["git"]);
            Assert.True(p["monorepo"]!["is_monorepo"]!.GetValue<bool>());
        }
        finally { RepoCheckouts.ForceDelete(root); }
    }

    [Fact]
    public async Task Skips_a_packages_directory_only_when_it_is_a_NuGet_cache()
    {
        var root = NewRoot();
        try
        {
            Write(root, "App.sln", "");
            Write(root, "src/App/App.csproj", "<Project ToolsVersion=\"15.0\"><PropertyGroup><TargetFrameworkVersion>v4.7.2</TargetFrameworkVersion></PropertyGroup></Project>");
            Write(root, "src/App/Program.cs", "class Program { }\n");
            Write(root, "packages/Newtonsoft.Json.13.0.1/Newtonsoft.Json.13.0.1.nupkg", "");
            Write(root, "packages/Newtonsoft.Json.13.0.1/lib/net45/Newtonsoft.Json.dll", "");
            var p = Reparse(await RepositoryDiagnosis.DiagnoseAsync(root, "dotnet", git: false));
            Assert.Equal(["src"], Strings(p["size"]!["top_level_dirs"]));
            Assert.Equal(3, p["size"]!["files"]!.GetValue<int>());
            Assert.True(p["windows_build"]!["legacy_netframework"]!.GetValue<bool>());
            Assert.Equal(["msbuild App.sln /t:Build   # requires Windows / Visual Studio build tools"], Strings(p["build"]!["commands"]));
        }
        finally { RepoCheckouts.ForceDelete(root); }
    }

    [Fact]
    public async Task Counts_NuGet_layouts_under_packages_and_nothing_else()
    {
        var root = NewRoot();
        try
        {
            Write(root, "packages/core/src/a.ts", "export const a = 1;\n");
            Write(root, "packages/core/package.json", "{}");
            Write(root, "vendor/x/y.js", "");
            await GitAsync(root, "init", "-q");
            await GitAsync(root, "add", "-A");
            await GitAsync(root, "commit", "-q", "-m", "x");
            var p = Reparse(await RepositoryDiagnosis.DiagnoseAsync(root, "pk"));
            Assert.Equal(1, p["git"]!["tracked_package_dirs"]!.GetValue<int>());
            Assert.Equal(3, p["git"]!["tracked_files"]!.GetValue<int>());
        }
        finally { RepoCheckouts.ForceDelete(root); }
    }

    /// <summary>
    /// Not in the old suite: git's own words never become data. A repository with no commits makes every history command
    /// fail; the old server read their stdout only, where <c>rev-parse HEAD</c> had echoed "HEAD" and the rest nothing.
    /// </summary>
    [Fact]
    public async Task Reads_a_repository_with_no_commits_from_stdout_only()
    {
        var root = NewRoot();
        try
        {
            Write(root, "src/a.ts", "export const a = 1;\n");
            await GitAsync(root, "init", "-q");
            var g = Reparse(await RepositoryDiagnosis.DiagnoseAsync(root, "empty"))["git"]!;
            Assert.Equal("HEAD", g["head"]!.GetValue<string>());
            Assert.Equal(0, g["tracked_files"]!.GetValue<int>());
            Assert.Equal(0, g["commits_in_clone"]!.GetValue<int>());
            Assert.False(g["shallow"]!.GetValue<bool>());
            Assert.Equal("", g["last_commit_date"]!.GetValue<string>());
            Assert.Equal("", g["first_commit_date_in_clone"]!.GetValue<string>());
            Assert.Equal(0, g["authors_in_clone"]!.GetValue<int>());
            Assert.Equal(0, g["commits_analyzed"]!.GetValue<int>());
            Same("[]", g["hot_files"]);
            Same("{}", g["churn_by_ext"]);
        }
        finally { RepoCheckouts.ForceDelete(root); }
    }

    /// <summary>Not in the old suite: the stored profile and the screen read the keys in the order the old server wrote them.</summary>
    [Fact]
    public void Keeps_every_key_in_the_order_the_old_server_wrote_it()
    {
        static List<string> Keys(JsonNode? o) => o!.AsObject().Select(kv => kv.Key).ToList();
        Assert.Equal(["name", "path", "languages", "frameworks", "package_managers", "build", "tests", "lint_format", "ci", "monorepo", "generated_code",
            "secrets", "external_systems", "ai_config", "docs", "windows_build", "environment", "size", "git"], Keys(P));
        Assert.Equal(["frameworks", "test_files", "test_dirs"], Keys(P["tests"]));
        Assert.Equal(["present", "systems", "workflows", "commands", "workflow_count"], Keys(P["ci"]));
        Assert.Equal(["is_monorepo", "workspaces", "packages", "package_count"], Keys(P["monorepo"]));
        Assert.Equal(["readme", "readme_bytes", "docs_dir", "docs_files", "adrs", "contributing", "architecture_docs", "license", "changelog", "license_kind",
            "pr_template", "codeowners"], Keys(P["docs"]));
        Assert.Equal(["sln", "csproj", "snk", "vbproj", "packages_config", "ps1", "bat_cmd", "legacy_netframework", "dll_checked_in", "exe_checked_in",
            "windows_only_build"], Keys(P["windows_build"]));
        Assert.Equal(["available", "head", "tracked_files", "tracked_binaries_dll_exe_pdb", "tracked_ide_junk", "tracked_package_dirs", "commits_in_clone", "shallow",
            "last_commit_date", "first_commit_date_in_clone", "authors_in_clone", "hot_files", "hot_dirs", "repeated_change_shapes", "cochange_pairs",
            "commits_analyzed", "churn_by_ext"], Keys(P["git"]));
        Assert.Matches("^[0-9a-f]{40}$", P["git"]!["head"]!.GetValue<string>());
    }
}
